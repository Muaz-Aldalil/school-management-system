import { writeFileSync } from 'fs';
import { join } from 'path';

const version = Date.now().toString(36);
const content = `// Auto-generated by scripts/set-build-version.js — do not edit manually\nexport const BUILD_VERSION = '${version}';\n`;

writeFileSync(join(process.cwd(), 'src', 'lib', 'build-version.js'), content);
console.log(`Build version: ${version}`);
